def ling_review_lines(loc: dict) -> list:
    """[] for English; otherwise the local-language line followed by the English line."""
    r = loc.get("linguistic_review")
    return [r["text"], r["text_en"]] if r else []


_NUM = re.compile(r"\d+\.\d+")


def verify_localization(report: dict, loc: dict) -> dict:
    """Check that a localised report carries exactly the English report's ids, versions, FDI numbers, values and labels."""
    problems = []
    text = " ".join([loc["summary"], *[f["narrative"] for f in loc["findings"]]])
    en = localize_report(report, "en")
    en_text = " ".join([en["summary"], *[f["narrative"] for f in en["findings"]]])
    if [f["finding_id"] for f in loc["findings"]] != [f["finding_id"] for f in report.get("findings", [])]:
        problems.append("finding ids differ from the English report")
    for f in report.get("findings", []):
        if f["finding_id"] not in text:
            problems.append(f"{f['finding_id']} missing from localised text")
    for k, v in (report.get("model_versions") or {"detection": report.get("model_version")}).items():
        needed = k in ("detection", "numbering", "segmentation") or any(f.get("kind") in ("closest_class", "abstained", "class_unavailable") for f in report.get("findings", []))
        if report.get("findings") and v and needed and v not in loc["summary"]:
            problems.append(f"{k} model version '{v}' missing from localised summary")
    if sorted(_NUM.findall(text)) != sorted(_NUM.findall(en_text)):
        problems.append("decimal values (scores/uncertainties) differ from the English report")
    for a, b in zip(report.get("findings", []), loc["findings"]):
        for key in ("tooth_fdi", "label", "probability", "uncertainty", "review_status", "kind"):
            if a.get(key) != b.get(key):
                problems.append(f"{a['finding_id']}: structured field '{key}' changed")
        if a.get("label") and a["label"] not in b["label_display"]:
            problems.append(f"{a['finding_id']}: original class name not preserved")
        if a.get("tooth_fdi") is not None and str(a["tooth_fdi"]) not in b["narrative"]:
            problems.append(f"{a['finding_id']}: FDI number missing")
    if loc["status"] != report.get("status"):
        problems.append("report status changed")
    a, b = report.get("final_result"), loc.get("final_result")
    if bool(a) != bool(b) or (a and (a["status"] != b["status"] or
                                    [(f["label"], f.get("score"), f.get("fdi")) for f in a.get("findings", [])] !=
                                    [(f["label"], f.get("score"), f.get("fdi")) for f in b.get("findings", [])])):
        problems.append("final result differs from the English report")
    return {"passed": not problems, "problems": problems, "lang": loc["lang"]}


