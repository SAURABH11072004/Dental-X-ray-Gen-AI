def render_text_localized(loc: dict) -> str:
    h = loc["headings"]
    out = [loc["title"], "=" * len(loc["title"]), f"[{loc['status_text']}] {loc['disclaimer']}", *ling_review_lines(loc), "",
           f"{h['report']}: {loc['report_id']} | {h['image']}: {loc['image_id']} | "
           f"{h['models']}: {', '.join(f'{k}: {v}' for k, v in loc['model_versions'].items())} | {h['generated']}: {loc['generated_by']}", "",
           *([loc["final_result"]["heading"], loc["final_result"]["text"]] + ([loc["final_result"]["message"]] if loc["final_result"].get("message") else []) + [""]
             if loc.get("final_result") else []),
           h["summary"], loc["summary"], "", h["findings"]]
    out += [f"- {f['narrative']}" for f in loc["findings"]]
    sc = (loc.get("analysis") or {}).get("summary_counts")
    if sc:
        out += ["", " | ".join(f"{k.replace('n_', '').replace('_', ' ')}: {v}" for k, v in sc.items())]
    rv = [f for f in loc["findings"] if f.get("needs_review")]
    if rv:
        out += ["", loc["headings_review"]] + [f"- {f['finding_id']} - {f['tooth_fdi'] if f['tooth_fdi'] is not None else loc['unassigned']} - {'; '.join(f['review_reasons_text']) or '-'}" for f in rv]
    out += ["", h["limitations"]] + [f"- {x}" for x in loc["limitations"]] + ["", loc["note"], ""]
    return "\n".join(out)
