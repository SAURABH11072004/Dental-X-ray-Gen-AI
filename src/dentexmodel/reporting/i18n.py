def localize_final_result(fr: dict | None, lang: str) -> dict | None:
    """Same structure and values as the English final result; only the words change (class names keep the English label)."""
    if not fr:
        return None
    t = FINAL[lang]
    items = []
    for f in fr.get("findings", []):
        where = t["tooth"].format(n=f["fdi"]) if f.get("fdi") is not None else t["region"].format(n=f.get("region_no") or "?")
        items.append({**f, "label_display": _label(lang, f["label"]),
                      "text": f"{_label(lang, f['label'])} ({where}, {t['score'].format(p=_fmt(f.get('score')))}"
                              + (f"; {t['high_unc']}" if f.get("high_uncertainty") else "") + ")"})
    label = t.get(fr["status"], fr.get("label"))
    line = f"{label}: " + "; ".join(i["text"] for i in items) if items else label
    return {**fr, "label_display": label, "heading": t["heading"], "findings": items, "text": line}


def _fmt(v, nd=2) -> str:
    return "n/a" if v is None else f"{float(v):.{nd}f}"


def _label(lang: str, label) -> str:
    """Target-language class name with the original dataset label kept in brackets."""
    if label is None:
        return "-"
    if lang == "en":
        return str(label)
    local = LABELS[lang].get(str(label))
    return f"{local} ({label})" if local else str(label)


def _check_lang(lang: str) -> str:
    lang = (lang or DEFAULT_LANG).lower()
    if lang not in LANGUAGES:
        raise ValueError(f"unsupported language '{lang}'; supported: {sorted(LANGUAGES)}")
    return lang


def localize_report(report: dict, lang: str = DEFAULT_LANG) -> dict:
    """Render ``report`` (the validated English report dict) in ``lang``. Pure function of the structured findings."""
    lang = _check_lang(lang)
    t = T[lang]
    findings = report.get("findings", [])
    versions = report.get("model_versions") or {"detection": report.get("model_version")}
    lines = []
    if not findings:
        lines.append(t["no_findings"])
    else:
        lines.append(t["detected"].format(m=versions.get("detection", report.get("model_version")), n=len(findings)))
        if versions.get("segmentation"):
            lines.append(t["segmented"].format(m=versions["segmentation"]))
        if versions.get("numbering"):
            lines.append(t["numbered"].format(m=versions["numbering"]))
        if versions.get("classification"):
            lines.append(t["classified"].format(m=versions["classification"]))
    c = (report.get("analysis") or {}).get("summary_counts")
    if findings and c:
        lines.append(t["counts"].format(a=c["n_numbered"], b=c["n_with_mask"], c=c["n_review_required"]))
    rows = []
    for f in findings:
        tooth = t["tooth"].format(n=f["tooth_fdi"]) if f.get("tooth_fdi") is not None else t["unnumbered"]
        rs = t["review"].get(f.get("review_status"), str(f.get("review_status")))
        if f.get("kind") == "abstained":        # legacy reports only (before 2026-10-16)
            narrative = t["abstained"].format(fid=f["finding_id"], tooth=tooth, u=_fmt(f.get("uncertainty")), rs=rs)
        elif f.get("kind") == "class_unavailable":
            narrative = t["unavailable"].format(fid=f["finding_id"], tooth=tooth, rs=rs)
        elif f.get("kind") == "closest_class":
            narrative = t["closest"].format(fid=f["finding_id"], tooth=tooth, label=_label(lang, f.get("label")),
                                            p=_fmt(f.get("probability")), u=_fmt(f.get("uncertainty")), rs=rs,
                                            hu=t["high_unc"] if f.get("high_uncertainty") else "")
        else:
            narrative = t["region"].format(fid=f["finding_id"], tooth=tooth, p=_fmt(f.get("probability"), 3), rs=rs)
        rows.append({"finding_id": f["finding_id"], "tooth_fdi": f.get("tooth_fdi"), "kind": f.get("kind"),
                     "label": f.get("label"), "label_display": _label(lang, f.get("label")),
                     "probability": f.get("probability"), "uncertainty": f.get("uncertainty"),
                     "class_scores": f.get("class_scores"), "high_uncertainty": bool(f.get("high_uncertainty")),
                     "review_status": f.get("review_status"), "review_status_text": rs, "narrative": narrative,
                     "region_id": f.get("region_id"), "region_no": f.get("region_no"), "needs_review": bool(f.get("needs_review")),
                     "review_reasons": f.get("review_reasons") or [],
                     "review_reasons_text": [FLAGS[lang].get(x, x) for x in (f.get("review_reasons") or [])],
                     "numbering_status": f.get("numbering_status"),
                     "evidence_region": f.get("evidence_region")})
    return {
        "lang": lang, "lang_name": LANGUAGES[lang], "title": t["title"],
        "status": report.get("status"), "status_text": t["status"].get(report.get("status"), str(report.get("status"))),
        "disclaimer": t["disclaimer"], "summary": " ".join(lines), "findings": rows, "limitations": list(t["limitations"]),
        "headings": t["h"], "columns": t["cols"], "unassigned": t["unassigned"],
        "report_id": report.get("report_id"), "image_id": report.get("image_id"), "model_versions": versions,
        "analysis": report.get("analysis") or {}, "headings_review": {"en": "Regions requiring manual review", "hi": "मैन्युअल समीक्षा आवश्यक क्षेत्र", "mr": "मॅन्युअल पुनरावलोकन आवश्यक भाग"}[lang],
        "generated_by": report.get("generated_by"), "reviewed_by": report.get("reviewed_by"),
        "final_result": localize_final_result(report.get("final_result"), lang),
        "note": t["note"] + ("" if lang == "en" else ""),
        "translation_reviewed_by_native_dental_professional": False if lang != "en" else None,
        "linguistic_review": None if lang == "en" else {"status": "awaiting_linguistic_review", "text": LING_REVIEW[lang], "text_en": LING_REVIEW_EN},
    }


