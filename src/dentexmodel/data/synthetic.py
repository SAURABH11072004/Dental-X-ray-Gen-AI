"""SYNTHETIC TEST FIXTURES - software testing only.

Generated images are abstract blobs, not radiographs. Everything written here carries a visible marker file
and manifest rows are tagged ``dataset_source`` containing ``SYNTHETIC``. The discovery layer only scans the
fixture directory when ``include_synthetic=True`` and never counts it toward the main dataset.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image

from dentexmodel.data.discovery import SYNTHETIC_DIR

MARKER = "TEST_DATA_SYNTHETIC.txt"
MARKER_TEXT = ("SYNTHETIC TEST DATA - generated by dentexmodel.data.synthetic for software tests.\n"
               "These are NOT dental radiographs and must never be used for training, evaluation or reported results.\n")


def make_blob_image(seed: int, w: int = 512, h: int = 256) -> np.ndarray:
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:h, 0:w]
    img = 0.15 + 0.1 * rng.random((h, w))
    for _ in range(12):
        cx, cy = rng.integers(0, w), rng.integers(0, h)
        r = rng.integers(10, 40)
        img += 0.5 * np.exp(-((xx - cx) ** 2 + (yy - cy) ** 2) / (2 * r * r))
    return np.clip(img, 0, 1).astype(np.float32)


def write_synthetic_dataset(data_root: Path, n_images: int = 12, with_annotations: bool = True, seed: int = 0) -> Path:
    """Write ``<data_root>/_synthetic_test/synthetic/xrays/*.png`` (+ COCO json) and return the fixture dir."""
    base = Path(data_root) / SYNTHETIC_DIR / "synthetic"
    xr = base / "xrays"
    xr.mkdir(parents=True, exist_ok=True)
    (Path(data_root) / SYNTHETIC_DIR / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    rng = np.random.default_rng(seed)
    images, anns = [], []
    aid = 1
    for i in range(n_images):
        arr = make_blob_image(seed * 1000 + i)
        h, w = arr.shape
        Image.fromarray((arr * 255).astype(np.uint8), mode="L").save(xr / f"synth_{i}.png")
        images.append({"id": i, "file_name": f"synth_{i}.png", "width": w, "height": h})
        for _ in range(int(rng.integers(1, 4))):
            x, y = int(rng.integers(0, w - 60)), int(rng.integers(0, h - 60))
            q, pos = int(rng.integers(0, 4)), int(rng.integers(0, 8))
            anns.append({"id": aid, "image_id": i, "bbox": [x, y, 40, 50], "area": 2000,
                         "segmentation": [[x, y, x + 40, y, x + 40, y + 50, x, y + 50]] if rng.random() < 0.5 else [],
                         "category_id_1": q, "category_id_2": pos, "category_id_3": int(rng.integers(0, 4))})
            aid += 1
    if with_annotations:
        coco = {"images": images, "annotations": anns,
                "categories_1": [{"id": k, "name": str(k + 1)} for k in range(4)],
                "categories_2": [{"id": k, "name": str(k + 1)} for k in range(8)],
                "categories_3": [{"id": 0, "name": "Caries"}, {"id": 1, "name": "DeepCaries"},
                                 {"id": 2, "name": "Impacted"}, {"id": 3, "name": "PeriapicalLesion"}],
                "info": {"description": "SYNTHETIC TEST DATA - not real"}}
        (base / "synthetic_quadrant_enumeration_disease.json").write_text(json.dumps(coco), encoding="utf-8")
    return base


def write_simulated_main_layout(tmp_root: Path, n_images: int = 24, seed: int = 0) -> Path:
    """For unit tests ONLY: lay the synthetic fixture out exactly like the real dataset inside a *temporary*
    data root so discovery/validation/splitting/pipeline code paths can be exercised end to end.
    Refuses to write anywhere outside the system temp directory."""
    import tempfile
    tmp_root = Path(tmp_root).resolve()
    if Path(tempfile.gettempdir()).resolve() not in tmp_root.parents and tmp_root != Path(tempfile.gettempdir()).resolve():
        raise RuntimeError("write_simulated_main_layout only writes inside the system temp directory (test use only).")
    base = write_synthetic_dataset(tmp_root, n_images=n_images, seed=seed)
    dest = tmp_root / "training_data" / "quadrant_enumeration_disease"
    dest.parent.mkdir(parents=True, exist_ok=True)
    import shutil
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(base, dest)
    (dest / "synthetic_quadrant_enumeration_disease.json").rename(dest / "train_quadrant_enumeration_disease.json")
    (dest / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    shutil.rmtree(tmp_root / SYNTHETIC_DIR)
    return dest
