import { chromium } from "playwright-core";
import fs from "node:fs";
const BASE = "http://localhost:5173";
const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(BASE + "/analysis", { waitUntil: "networkidle" });
await page.selectOption("#src", "uploads");
await page.waitForTimeout(1200);
const opts = await page.locator('select[aria-label="Image"] option').allInnerTexts();
const idx = opts.findIndex((t) => t.startsWith("val_12"));
await page.locator('select[aria-label="Image"]').selectOption({ index: idx });
await page.waitForTimeout(1200);
const [fr] = await Promise.all([page.waitForResponse((r) => r.url().includes("/api/analyze/full"), { timeout: 240000 }), page.getByTestId("run-full").click()]);
const full = await fr.json();
await page.waitForSelector('[data-testid="region-table"] tbody tr');
await page.waitForTimeout(1000);
const geo = await page.evaluate(() => {
  const boxes = [...document.querySelectorAll('[data-testid="detection-box"] > rect')].map((r) => ({ x: +r.getAttribute("x"), y: +r.getAttribute("y"), w: +r.getAttribute("width"), h: +r.getAttribute("height") }));
  const svg = document.querySelector('[data-testid="detection-box"]')?.closest("svg");
  const img = svg?.parentElement?.querySelector("img");
  const ir = img?.getBoundingClientRect(), sr = svg?.getBoundingClientRect();
  return { boxes, vb: svg?.getAttribute("viewBox"), nat: img ? [img.naturalWidth, img.naturalHeight] : null, imgRect: ir && [ir.x, ir.y, ir.width, ir.height], svgRect: sr && [sr.x, sr.y, sr.width, sr.height] };
});
const [W, H] = full.image_size;
const near = (b, g) => Math.abs(b.x - g.box[0]) < 0.01 && Math.abs(b.y - g.box[1]) < 0.01 && Math.abs(b.w - (g.box[2] - g.box[0])) < 0.01 && Math.abs(b.h - (g.box[3] - g.box[1])) < 0.01;
const probs = [];
if (!geo.nat || geo.nat[0] !== W || geo.nat[1] !== H) probs.push(`natural size ${geo.nat} != api ${W}x${H}`);
if (geo.vb !== `0 0 ${W} ${H}`) probs.push(`viewBox ${geo.vb}`);
if (geo.imgRect && geo.svgRect && geo.imgRect.some((v, i) => Math.abs(v - geo.svgRect[i]) > 1.5)) probs.push(`img rect ${geo.imgRect} != svg rect ${geo.svgRect}`);
geo.boxes.forEach((b, i) => { if (!full.regions.some((g) => near(b, g))) probs.push(`drawn rect ${i} matches no API box`); });
const hidden = full.regions.filter((g) => !geo.boxes.some((b) => near(b, g)));
if (hidden.length) probs.push(`${hidden.length} API regions not drawn`);
// screen-space check: a rendered box's on-screen position equals scale * API coordinate (scale = svg css width / image width)
const scale = geo.svgRect[2] / W;
const first = await page.locator('[data-testid="detection-box"] > rect').first().boundingBox();
const g0 = full.regions[0];
const expX = geo.svgRect[0] + g0.box[0] * scale, expY = geo.svgRect[1] + g0.box[1] * scale;
const screenOK = Math.abs(first.x - expX) < 3 && Math.abs(first.y - expY) < 3;
console.log(JSON.stringify({ image: full.image_id, api_size: [W, H], natural: geo.nat, viewBox: geo.vb, drawn: geo.boxes.length, regions: full.regions.length, problems: probs, screen_space_first_box_ok: screenOK, first_box_screen: [first.x, first.y], expected: [expX, expY], scale }));
fs.writeFileSync("D:/Dentex-Gen Ai/docs/audit_evidence/overlay_geometry.json", JSON.stringify({ image: full.image_id, api_size: [W, H], natural: geo.nat, viewBox: geo.vb, drawn: geo.boxes.length, regions: full.regions.length, problems: probs, screen_space_first_box_ok: screenOK }, null, 1));
await page.screenshot({ path: "D:/Dentex-Gen Ai/docs/audit_evidence/shots/overlay_geometry.png" });
await browser.close();
